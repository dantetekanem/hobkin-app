const script: SampleFile = {
  path: 'script/production_errors.rb',
  status: 'added',
  base: null,
  head: lines(
    '#!/usr/bin/env ruby',
    '# frozen_string_literal: true',
    '',
    '# Prints the errors production raised since a time, a day ago unless one is given, most frequent first.',
    '#   ERRORS_URL=https://monitor.example ERRORS_TOKEN=... script/production_errors.rb [since]',
    "require 'json'",
    "require 'net/http'",
    "require 'time'",
    '',
    'module ProductionErrors',
    '  module_function',
    '',
    '  # The errors the production monitor holds since a time. The token is read from ERRORS_TOKEN.',
    '  def fetch_errors(since, http: Net::HTTP)',
    '    uri = URI("#{ENV.fetch(\'ERRORS_URL\')}/errors?since=#{since.utc.iso8601}")',
    '    request = Net::HTTP::Get.new(uri)',
    '    request[\'Authorization\'] = "Bearer #{ENV.fetch(\'ERRORS_TOKEN\')}"',
    '    response = http.start(uri.host, uri.port, use_ssl: true) { |connection| connection.request(request) }',
    '    raise "The monitor answered #{response.code}" unless response.is_a?(Net::HTTPSuccess)',
    '',
    '    body = response.body.to_s',
    "    JSON.parse(body.empty? ? '[]' : body)",
    '  end',
    '',
    '  # One line per message: how often it was raised, when last, and the message cut to fit.',
    '  def report(errors)',
    "    return 'No errors in production.' if errors.empty?",
    '',
    "    rows = errors.group_by { |error| error['message'] }.map do |message, all|",
    "      [all.size, all.map { |error| error['at'] }.max, message]",
    '    end',
    '    rows.sort_by { |count, last, _| [-count, last] }',
    "        .map { |count, last, message| format('%5d  %s  %s', count, last, truncate(message)) }",
    '        .join("\\n")',
    '  end',
    '',
    '  def truncate(message, width: 72)',
    '    message.length > width ? "#{message[0, width - 1]}…" : message',
    '  end',
    'end',
    '',
    'if $PROGRAM_NAME == __FILE__',
    '  since = ARGV.first ? Time.parse(ARGV.first) : Time.now - 86_400',
    '  puts ProductionErrors.report(ProductionErrors.fetch_errors(since))',
    'end',
  ),
}

